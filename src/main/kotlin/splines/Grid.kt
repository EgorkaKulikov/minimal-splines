package numerics

// ============================================================================
// 4. СЕТКА (net): тройные узлы на концах
// ============================================================================

/**
 * Сетка X: a=x_{-2}=x_{-1}=x_0 < x_1 < ... < x_{n-1} < x_n=x_{n+1}=x_{n+2}=b
 * с узлами кратности 3 на концах. Хранит x_j для j = -2 .. n+2; idx(j)=j+2.
 *
 * @param n число внутренних интервалов.
 * @param interior внутренние узлы x_0..x_n (размер n+1), включая концы a и b.
 * @throws IllegalArgumentException если n < 1, размер interior не равен n+1 либо узлы не
 *   строго возрастают.
 */
class Grid(val n: Int, interior: DoubleArray) {
    init {
        // n >= 1: при n = 0 нет ни одного интервала, и вычисление h = max_j(...) упало бы на
        // пустом диапазоне невнятным NoSuchElementException.
        require(n >= 1) { "Grid: требуется n >= 1 (нужен хотя бы один интервал), получено n=$n" }
        require(interior.size == n + 1) {
            "interior должен иметь размер n+1=${n + 1}, получено ${interior.size}"
        }
        // Строгая монотонность — не косметика: на ней держатся h = max_j (x_{j+1}-x_j),
        // бинарный поиск интервала в MinimalSplineBasis.intervalOf и носители сплайнов
        // [x_j, x_{j+3}]. Нарушение не даёт исключения внутри алгоритмов — оно даёт тихо
        // неверные числа, поэтому отбраковываем сразу при построении сетки.
        for (i in 0 until n) require(interior[i] < interior[i + 1]) {
            "Grid: узлы должны строго возрастать; нарушено на i=$i: " +
                "x[$i]=${interior[i]} не меньше x[${i + 1}]=${interior[i + 1]}"
        }
    }

    val a: Double = interior.first()
    val b: Double = interior.last()

    /**
     * Узлы x_{-2..n+2}, длина n+5; idx(j) = j+2.
     *
     * `private`: единственный читатель — аксессор [x]. Снаружи массив не читался нигде,
     * а публичным он давал внешнему коду возможность тихо сломать инвариант строгого
     * возрастания, проверенный в `init`, уже после построения сетки.
     */
    private val knots: DoubleArray = DoubleArray(n + 5).also { arr ->
        arr[idx(-2)] = interior[0]; arr[idx(-1)] = interior[0]
        for (j in 0..n) arr[idx(j)] = interior[j]
        arr[idx(n + 1)] = interior[n]; arr[idx(n + 2)] = interior[n]
    }

    /** Шаг h = max_j (x_{j+1} - x_j) по внутренним интервалам. */
    val h: Double = (0 until n).maxOf { interior[it + 1] - interior[it] }

    /**
     * Допуск включения точки разбиения: узел считается строго внутри подынтервала,
     * если отстоит от его конца более чем на эту величину.
     *
     * ЕДИНЫЙ ИСТОЧНИК для всех потребителей (`VolterraOperator`, `SplineSpace`):
     * раньше константа и формула дублировались в двух классах, причём записаны были
     * по-разному (`maxOf` против `coerceAtLeast`) — расхождение было бы вопросом времени.
     *
     * Порог ОТНОСИТЕЛЕН ТОЛЬКО ВВЕРХ. Формула `1e-15 * maxOf(1.0, |b-a|)` растёт
     * вместе с отрезком, но НЕ уменьшается на мелких: при `|b-a| < 1` она даёт всё те
     * же `1e-15`, то есть В ОТНОСИТЕЛЬНЫХ ЕДИНИЦАХ СТАНОВИТСЯ ГРУБЕЕ, чем на единичном
     * отрезке. Это ОСОЗНАННОЕ следствие выбранной формулы: нижняя граница `1.0`
     * гарантирует ПОБИТОВОЕ совпадение с прежним абсолютным 1e-15 на дефолтном `[0,1]`
     * (умножение на `1.0` в IEEE-754 точное), чем и обеспечена нейтральность миграции
     * относительно характеризационного эталона. Масштабирование вниз потребовало бы
     * перегенерации эталона и в задачу не входило.
     *
     * Зачем вообще относительный: абсолютные 1e-15 на отрезке масштаба ~1e3 лежат ниже
     * ulp самих узлов (`ulp(1e3) ~ 2.3e-13`), и вычитание не меняет число ни на бит —
     * критерий вырождается в строгое сравнение и перестаёт быть допуском.
     */
    val breakpointInclusionEps: Double = BREAKPOINT_INCLUSION_EPS_UNIT * maxOf(1.0, kotlin.math.abs(b - a))

    /** Отображение математического индекса j в индекс массива. */
    fun idx(j: Int): Int = j + 2

    /** Узел x_j по математическому индексу j (-2..n+2). */
    fun x(j: Int): Double = knots[idx(j)]

    /**
     * Совпадают ли соседние узлы x_j и x_{j+1} (то есть вырожден ли интервал [x_j, x_{j+1}]).
     *
     * Ответ даётся ПО ИНДЕКСУ, без сравнения значений Double. Это корректно, потому что
     * кратность узлов здесь порождается ИСКЛЮЧИТЕЛЬНО паддингом краёв в [knots]:
     *   x_{-2} = x_{-1} = x_0 = a  и  x_n = x_{n+1} = x_{n+2} = b,
     * а все внутренние узлы x_0 < x_1 < ... < x_n строго возрастают — это инвариант,
     * проверяемый в `init`. Поэтому совпадение возможно только при j < 0 (левый тройной
     * узел) или j >= n (правый тройной узел).
     *
     * Сравнение `x(j) == x(j+1)` давало бы тот же ответ, но через точное равенство Double,
     * что прячет истинную причину (структура сетки, а не арифметика) и выглядит как
     * ненадёжное сравнение вещественных чисел.
     *
     * @param j левый индекс пары; допустимый диапазон -2..n+1 (чтобы оба узла x_j и
     *   x_{j+1} лежали в хранимом диапазоне -2..n+2).
     * @throws IllegalArgumentException если j вне -2..n+1.
     */
    fun isCoincident(j: Int): Boolean {
        require(j in -2..n + 1) {
            "Grid.isCoincident: требуется j в -2..${n + 1} (пара x_j, x_{j+1}), получено j=$j"
        }
        return j < 0 || j >= n
    }

    /**
     * Внутренние узлы x_0..x_n (размер n+1) — точки разрыва для квадратуры.
     *
     * READ-ONLY ПО СОГЛАШЕНИЮ: содержимое НЕЛЬЗЯ изменять. Геттер СОЗНАТЕЛЬНО не
     * возвращает копию: это ГОРЯЧЕЕ поле. Его читают на КАЖДОЕ применение
     * интегрального оператора (`FredholmOperator.apply`/`applyDeriv`/`applyDeriv2`,
     * `VolterraOperator.subBreakpoints`/`apply`/`integrateRange`, `UrysohnOperator.apply`),
     * то есть десятки тысяч раз за один запуск. Копирование на каждом обращении
     * добавило бы аллокацию в горячий цикл и откатило бы оптимизации кэширования.
     *
     * Записей в этот массив в проекте нет ни одной — соглашение фактически соблюдено.
     * На нём держится эквивалентность кэшированного и некэшированного путей Вольтерры
     * (см. `VolterraOperator.cellNodes`), поэтому нарушение соглашения даст не ошибку,
     * а тихо неверные числа.
     */
    val breakpoints: DoubleArray = DoubleArray(n + 1) { x(it) }

    companion object {
        /**
         * Базовый (безразмерный) допуск включения узла, отнесённый к единичному отрезку.
         *
         * Фактический порог — [breakpointInclusionEps]; напрямую в сравнениях НЕ используется.
         */
        const val BREAKPOINT_INCLUSION_EPS_UNIT = 1e-15

        /** Равномерная сетка: x_j = a + (b-a) j/n. */
        fun uniform(n: Int, a: Double = 0.0, b: Double = 1.0): Grid =
            Grid(n, DoubleArray(n + 1) { a + (b - a) * it / n })

        /**
         * Квазиравномерная сетка X^q: x_j = a + (b-a) Psi(j/n),
         * Psi(u) = u + amp*sin(2*pi*u) — гладкая монотонная с фиксированным (не
         * зависящим от n) параметром локальной квазиравномерности.
         *
         * Монотонность Psi НЕ автоматична: Psi'(u) = 1 + 2*pi*amp*cos(2*pi*u), т.е. Psi
         * строго возрастает КАК ФУНКЦИЯ лишь при |amp| < 1/(2*pi) ≈ 0.15915.
         *
         * Однако сетке нужна монотонность не самой Psi, а конечного набора УЗЛОВ Psi(j/n),
         * и это СЛАБЕЕ: при amp = 1/(2*pi) производная обращается в ноль в одной точке,
         * но узлы строго возрастают при n примерно до 5*10^5 (дальше шаг вблизи u = 1/2
         * уходит под ulp: кубический член теряется при округлении, и уже при n = 6*10^5
         * два соседних узла совпадают), а amp = 0.16 немонотонен только
         * при n >= 19 (при n = 8 узлы возрастают). Поэтому проверки НА САМ amp здесь нет:
         * она сужала бы публичный API, отбраковывая легитимные входы. Фактическая строгая
         * монотонность построенных узлов проверяется инвариантом [Grid] в его `init` — именно
         * то, что требуется, и ровно тогда, когда оно действительно нарушено.
         *
         * @param amp амплитуда возмущения; допустимо любое значение, при котором узлы
         *   строго возрастают; иначе [Grid] бросит IllegalArgumentException.
         */
        fun quasiUniform(n: Int, a: Double = 0.0, b: Double = 1.0, amp: Double = 0.04): Grid =
            Grid(n, DoubleArray(n + 1) { i ->
                val u = i.toDouble() / n
                a + (b - a) * (u + amp * Math.sin(2.0 * Math.PI * u))
            })

        /**
         * Геометрическая (неравномерная) сетка семейства sn-article:
         *   x_j = a + (b-a) (q^j - 1)/(q^n - 1),  q = R^{1/(n-1)},  j = 0..n.
         *
         * Фиксированное отношение крайних шагов h_{n-1}/h_0 = R; шаги растут
         * геометрически (h_j = (b-a) q^j (q-1)/(q^n-1)), так что локальный параметр
         * квазиравномерности постоянен: h_j/h_{j-1} = q =: mu_n, mu_n -> 1 при n->inf.
         * Сетка существенно неравномерна, но локально квазиравномерна.
         *
         * @param n число внутренних интервалов (>= 2).
         * @param R отношение крайних шагов (> 0). R=1 вырождается в равномерную.
         */
        fun geometric(n: Int, a: Double = 0.0, b: Double = 1.0, R: Double = 2.0): Grid {
            require(n >= 2) { "geometric: требуется n >= 2, получено n=$n" }
            require(R > 0.0) { "geometric: требуется R > 0, получено R=$R" }
            val q = Math.pow(R, 1.0 / (n - 1))
            if (kotlin.math.abs(q - 1.0) < 1e-15) {
                // Вырожденный случай R=1: равномерная сетка (q^n - 1 -> 0).
                return Grid(n, DoubleArray(n + 1) { a + (b - a) * it / n })
            }
            val denom = Math.pow(q, n.toDouble()) - 1.0
            return Grid(n, DoubleArray(n + 1) { j ->
                when (j) {
                    0 -> a
                    n -> b
                    else -> a + (b - a) * (Math.pow(q, j.toDouble()) - 1.0) / denom
                }
            })
        }

        /**
         * Градуированная двухмасштабная сетка с ФИКСИРОВАННЫМ (не зависящим от n)
         * параметром локальной квазиравномерности. Шаги чередуются между двумя
         * значениями s и ratio*s по шаблону s*(1, ratio, 1, ratio, ...), так что
         * отношение соседних шагов h_j/h_{j-1} равно ratio или 1/ratio при ЛЮБОМ n.
         * Нормировка: сумма шагов = b-a (интервал покрыт точно). При нечётном n
         * последний шаг остаётся непарным (одиночное значение шаблона).
         *
         * В отличие от geometric (mu_n = q -> 1 при n->inf), здесь mu = ratio
         * фиксировано: сетка остаётся существенно локально неравномерной при
         * измельчении (h->0), что и требуется для устойчиво большой константы
         * Лебега. Сетка локально квазиравномерна (соседние шаги ограничены), поэтому
         * минимальные сплайны на ней существуют.
         *
         * @param n число внутренних интервалов (>= 2).
         * @param ratio отношение соседних шагов (> 0). ratio=1 вырождается в равномерную.
         */
        fun graded(n: Int, a: Double = 0.0, b: Double = 1.0, ratio: Double = 2.0): Grid {
            require(n >= 2) { "graded: требуется n >= 2, получено n=$n" }
            require(ratio > 0.0) { "graded: требуется ratio > 0, получено ratio=$ratio" }
            // Множители шаблона: чётный индекс -> 1, нечётный -> ratio (пары s, ratio*s).
            val mult = DoubleArray(n) { if (it % 2 == 0) 1.0 else ratio }
            val sum = mult.sum()
            val s = (b - a) / sum // базовый шаг: нормировка на длину интервала
            val interior = DoubleArray(n + 1)
            interior[0] = a
            var acc = a
            for (i in 0 until n) { acc += s * mult[i]; interior[i + 1] = acc }
            interior[n] = b // защита от накопленной ошибки округления на правом конце
            return Grid(n, interior)
        }
    }
}
