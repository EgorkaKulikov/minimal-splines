package splines

// ============================================================================
// Сетка с кратными краевыми узлами
// ============================================================================

/**
 * Сетка X: a=x_{-2}=x_{-1}=x_0 < x_1 < ... < x_{n-1} < x_n=x_{n+1}=x_{n+2}=b
 * с узлами кратности 3 на концах. Хранит x_j для j = -2 .. n+2; idx(j)=j+2.
 *
 * @property n число внутренних интервалов.
 * @param interior внутренние узлы x_0..x_n (размер n+1), включая концы a и b.
 * @throws IllegalArgumentException если n < 1, размер interior не равен n+1 либо узлы не
 *   строго возрастают.
 */
public class Grid(public val n: Int, interior: DoubleArray) {
    init {
        // При n = 0 нет ни одного интервала, и шаг h = max_j (x_{j+1} - x_j) не определён.
        require(n >= 1) { "Grid: требуется n >= 1 (нужен хотя бы один интервал), получено n=$n" }
        require(interior.size == n + 1) {
            "interior должен иметь размер n+1=${n + 1}, получено ${interior.size}"
        }
        // Строгое возрастание узлов — инвариант, на котором основаны шаг h = max_j (x_{j+1} - x_j),
        // бинарный поиск интервала в MinimalSplineBasis и носители сплайнов [x_j, x_{j+3}];
        // он проверяется при построении сетки, поскольку алгоритмы его нарушение не обнаруживают.
        for (i in 0 until n) require(interior[i] < interior[i + 1]) {
            "Grid: узлы должны строго возрастать; нарушено на i=$i: " +
                "x[$i]=${interior[i]} не меньше x[${i + 1}]=${interior[i + 1]}"
        }
    }

    /** Левый конец отрезка a = x_0. */
    public val a: Double = interior.first()

    /** Правый конец отрезка b = x_n. */
    public val b: Double = interior.last()

    /**
     * Узлы x_{-2..n+2}, длина n+5; idx(j) = j+2. Доступ только через [x]: закрытый массив
     * сохраняет инвариант строгого возрастания, проверенный при построении.
     */
    private val knots: DoubleArray = DoubleArray(n + 5).also { arr ->
        arr[idx(-2)] = interior[0]; arr[idx(-1)] = interior[0]
        for (j in 0..n) arr[idx(j)] = interior[j]
        arr[idx(n + 1)] = interior[n]; arr[idx(n + 2)] = interior[n]
    }

    /** Шаг h = max_j (x_{j+1} - x_j) по внутренним интервалам. */
    public val h: Double = (0 until n).maxOf { interior[it + 1] - interior[it] }

    /**
     * Допуск включения точки разбиения: узел считается лежащим строго внутри подынтервала, если
     * отстоит от его конца более чем на эту величину.
     *
     * Вычисляется как `BREAKPOINT_INCLUSION_EPS_UNIT * max(1, |b - a|)`: допуск растёт вместе с
     * длиной отрезка, поскольку абсолютный допуск 1e-15 на отрезке масштаба 1e3 лежит ниже ulp
     * самих узлов (`ulp(1e3) ≈ 2.3e-13`) и вырождается в строгое сравнение. На отрезках длины
     * менее единицы допуск равен `BREAKPOINT_INCLUSION_EPS_UNIT`.
     */
    public val breakpointInclusionEps: Double = BREAKPOINT_INCLUSION_EPS_UNIT * maxOf(1.0, kotlin.math.abs(b - a))

    /** Отображение математического индекса j в индекс массива. */
    public fun idx(j: Int): Int = j + 2

    /** Узел x_j по математическому индексу j (-2..n+2). */
    public fun x(j: Int): Double = knots[idx(j)]

    /**
     * Признак совпадения соседних узлов x_j и x_{j+1}, то есть вырожденности интервала [x_j, x_{j+1}].
     *
     * Ответ определяется индексом без сравнения значений: кратные узлы порождаются только
     * краевыми тройками x_{-2} = x_{-1} = x_0 = a и x_n = x_{n+1} = x_{n+2} = b, а внутренние
     * узлы x_0 < x_1 < ... < x_n строго возрастают по инварианту сетки. Совпадение возможно
     * только при j < 0 (левый кратный узел) или j >= n (правый кратный узел); сравнение
     * `x(j) == x(j+1)` даёт тот же результат.
     *
     * @param j левый индекс пары; допустимый диапазон -2..n+1, при котором оба узла x_j и
     *   x_{j+1} лежат в хранимом диапазоне -2..n+2.
     * @throws IllegalArgumentException если j вне -2..n+1.
     */
    public fun isCoincident(j: Int): Boolean {
        require(j in -2..n + 1) {
            "Grid.isCoincident: требуется j в -2..${n + 1} (пара x_j, x_{j+1}), получено j=$j"
        }
        return j < 0 || j >= n
    }

    /**
     * Внутренние узлы x_0..x_n (размер n+1) — точки разрыва гладкости сплайна, границы
     * подынтервалов квадратуры.
     *
     * Массив не копируется; изменение его содержимого нарушает инварианты сетки.
     */
    public val breakpoints: DoubleArray = DoubleArray(n + 1) { x(it) }

    /** Фабрики сеток и базовый допуск включения узла. */
    public companion object {
        /**
         * Базовый (безразмерный) допуск включения узла, отнесённый к единичному отрезку.
         *
         * Фактический допуск — [breakpointInclusionEps]; непосредственно в сравнениях не используется.
         */
        public const val BREAKPOINT_INCLUSION_EPS_UNIT: Double = 1e-15

        /** Равномерная сетка: x_j = a + (b-a) j/n. */
        public fun uniform(n: Int, a: Double = 0.0, b: Double = 1.0): Grid =
            Grid(n, DoubleArray(n + 1) { a + (b - a) * it / n })

        /**
         * Квазиравномерная сетка X^q: x_j = a + (b-a) Psi(j/n), Psi(u) = u + amp sin(2 pi u) —
         * гладкое монотонное возмущение равномерной сетки с не зависящим от n параметром
         * локальной квазиравномерности.
         *
         * Функция Psi строго возрастает лишь при |amp| < 1/(2 pi) ≈ 0.15915, поскольку
         * Psi'(u) = 1 + 2 pi amp cos(2 pi u). Сетке требуется более слабое условие — строгое
         * возрастание конечного набора узлов Psi(j/n): при amp = 1/(2 pi) узлы строго возрастают
         * при n примерно до 5·10^5 (далее шаг вблизи u = 1/2 теряется при округлении), а при
         * amp = 0.16 узлы возрастают при n = 8 и перестают возрастать при n >= 19. Поэтому
         * параметр amp отдельно не ограничивается: строгое возрастание построенных узлов
         * проверяется инвариантом [Grid].
         *
         * @param amp амплитуда возмущения; допустимо любое значение, при котором узлы строго
         *   возрастают.
         * @throws IllegalArgumentException если построенные узлы не возрастают строго.
         */
        public fun quasiUniform(n: Int, a: Double = 0.0, b: Double = 1.0, amp: Double = 0.04): Grid =
            Grid(n, DoubleArray(n + 1) { i ->
                val u = i.toDouble() / n
                a + (b - a) * (u + amp * Math.sin(2.0 * Math.PI * u))
            })

        /**
         * Геометрическая (неравномерная) сетка:
         *   x_j = a + (b-a) (q^j - 1)/(q^n - 1),  q = R^{1/(n-1)},  j = 0..n.
         *
         * Фиксированное отношение крайних шагов h_{n-1}/h_0 = R; шаги растут
         * геометрически (h_j = (b-a) q^j (q-1)/(q^n-1)), так что локальный параметр
         * квазиравномерности постоянен: h_j/h_{j-1} = q =: mu_n, mu_n -> 1 при n->inf.
         * Сетка существенно неравномерна, но локально квазиравномерна.
         *
         * @param n число внутренних интервалов (>= 2).
         * @param R отношение крайних шагов (> 0). R=1 вырождается в равномерную.
         * @throws IllegalArgumentException если n < 2 или R <= 0.
         */
        public fun geometric(n: Int, a: Double = 0.0, b: Double = 1.0, R: Double = 2.0): Grid {
            require(n >= 2) { "geometric: требуется n >= 2, получено n=$n" }
            require(R > 0.0) { "geometric: требуется R > 0, получено R=$R" }
            val q = Math.pow(R, 1.0 / (n - 1))
            if (kotlin.math.abs(q - 1.0) < 1e-15) {
                // Вырожденный случай R=1: равномерная сетка (q^n - 1 -> 0).
                return Grid(n, DoubleArray(n + 1) { a + (b - a) * it / n })
            }
            val denom = Math.pow(q, n.toDouble()) - 1.0
            return Grid(n, DoubleArray(n + 1) { j ->
                when (j) {
                    0 -> a
                    n -> b
                    else -> a + (b - a) * (Math.pow(q, j.toDouble()) - 1.0) / denom
                }
            })
        }

        /**
         * Градуированная двухмасштабная сетка с не зависящим от n параметром локальной
         * квазиравномерности. Шаги чередуются между двумя значениями s и ratio*s по шаблону
         * s*(1, ratio, 1, ratio, ...), так что отношение соседних шагов h_j/h_{j-1} равно
         * ratio или 1/ratio при любом n.
         * Нормировка: сумма шагов = b-a (интервал покрыт точно). При нечётном n
         * последний шаг остаётся непарным (одиночное значение шаблона).
         *
         * В отличие от geometric (mu_n = q -> 1 при n->inf), здесь mu = ratio
         * фиксировано: сетка остаётся существенно локально неравномерной при
         * измельчении (h->0), что и требуется для устойчиво большой константы
         * Лебега. Сетка локально квазиравномерна (соседние шаги ограничены), поэтому
         * минимальные сплайны на ней существуют.
         *
         * @param n число внутренних интервалов (>= 2).
         * @param ratio отношение соседних шагов (> 0). ratio=1 вырождается в равномерную.
         * @throws IllegalArgumentException если n < 2 или ratio <= 0.
         */
        public fun graded(n: Int, a: Double = 0.0, b: Double = 1.0, ratio: Double = 2.0): Grid {
            require(n >= 2) { "graded: требуется n >= 2, получено n=$n" }
            require(ratio > 0.0) { "graded: требуется ratio > 0, получено ratio=$ratio" }
            // Множители шаблона: чётный индекс -> 1, нечётный -> ratio (пары s, ratio*s).
            val mult = DoubleArray(n) { if (it % 2 == 0) 1.0 else ratio }
            val sum = mult.sum()
            val s = (b - a) / sum // базовый шаг: нормировка на длину интервала
            val interior = DoubleArray(n + 1)
            interior[0] = a
            var acc = a
            for (i in 0 until n) { acc += s * mult[i]; interior[i + 1] = acc }
            interior[n] = b // защита от накопленной ошибки округления на правом конце
            return Grid(n, interior)
        }
    }
}
