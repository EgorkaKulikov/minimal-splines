/**
 * Единый ОТНОСИТЕЛЬНЫЙ порог значимости скалярной величины (определителя,
 * знаменателя, вронскиана) на её собственном масштабе.
 *
 * ЗАЧЕМ ОТНОСИТЕЛЬНЫЙ. Прежде во всех проверках стоял АБСОЛЮТНЫЙ порог `1e-14`.
 * Он не масштабно-инвариантен: определитель `det(M_k)` матрицы аппроксимационного
 * соотношения ведёт себя как `h^3`, поэтому уже при `h ~ 1e-5` (или на коротком
 * отрезке `[0, 1e-6]`) абсолютно корректная задача отбраковывалась как «singular»,
 * а на отрезке масштаба `1e+6` практически вырожденная матрица (`det` — чистый
 * шум округления) проходила проверку и давала молча неверный ответ.
 *
 * ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Все защищаемые величины — это АЛГЕБРАИЧЕСКИЕ СУММЫ
 * произведений входных данных (`det3`, `dot3`, вронскиан, знаменатель `K1`).
 * Их реальная опасность — потеря значимости: результат вычитания оказывается
 * неотличим от шума округления слагаемых. Поэтому масштабом служит сумма модулей
 * слагаемых (см. [cancellationScale]), а критерий значимости —
 * `abs(value) > DEGENERACY_RELATIVE_EPS * scale` (см. [isSignificant]).
 *
 * ОТКУДА ЗНАЧЕНИЕ 1e-12. Машинный эпсилон double — 2.2e-16. Слагаемые
 * определителя 3x3 — произведения трёх сомножителей, каждое накапливает до
 * ~3 ulp, а сумма шести слагаемых — ещё до ~6 ulp: суммарный шум порядка
 * `1e-15 * scale`. Запас в три порядка (1e-12) отделяет «величина потеряна
 * в шуме» от «величина мала, но достоверна».
 *
 * ИЗМЕРЕННЫЙ ЗАПАС НА СЕТКАХ ЭТАЛОНА (`[0,1]`, системы B/H/T). Минимальное по
 * всем вызовам `invert3` отношение `det/scale`:
 *  - `n = 8`  — 4.2e-4 (B), 1.1e-4 (H), 3.4e-4 (T); минимум 1.1e-4;
 *  - `n = 64` — 6.6e-7 (B), 1.8e-7 (H), 6.9e-7 (T); минимум 1.8e-7.
 * То есть запас над порогом 1e-12 составляет ~5..6 порядков при `n = 64`.
 *
 * ГРАНИЦА ПРИМЕНИМОСТИ ПО `n`. На `[0,1]` отношение ведёт себя как
 * `det/scale ~ (h/(b-a))^3`, то есть падает как `n^-3`, и при пороге 1e-12
 * критерий начинает отбраковывать законные входы примерно при `n ~ 4*10^3`
 * (измерено: H — при `n >= 4096`, B и T — при `n >= 8192`). Максимальное `n`,
 * фактически используемое в проекте, — 256 (конфигурация бенчмарка:
 * `demo/bench/Benchmark.kt`, `problemSizes = [16, 32, 64, 128, 256]`, `speedupSize = 256`),
 * так что запас по `n` около 16x. Измеренный минимум при `n = 256` на
 * `Grid.uniform` — 2.8e-9 (H), 1.0e-8 (B), 1.1e-8 (T).
 *
 * ЧЕСТНОЕ СРАВНЕНИЕ СО СТАРЫМ АБСОЛЮТНЫМ ПОРОГОМ. Прежний критерий
 * `|det| >= 1e-14` на измельчении держался дольше — примерно до `n ~ 32768`.
 * Значит, НА ИЗМЕЛЬЧЕНИИ относительный критерий СТРОЖЕ абсолютного: он
 * отбраковывает раньше (в ~4..8 раз меньшее `n`). Это осознанная плата за
 * масштабную инвариантность: взамен критерий перестаёт зависеть от единиц
 * измерения и от длины отрезка — на коротком отрезке он больше не отбраковывает
 * корректную задачу, а на длинном больше не пропускает чистый шум округления.
 *
 * СУЖЕНИЕ КОНТРАКТА ОТНОСИТЕЛЬНО ПРЕЖНЕГО АБСОЛЮТНОГО ПОРОГА. Относительный
 * критерий отвергает часть входов, которые прежняя проверка `|value| >= 1e-14`
 * принимала, — а именно входы на доменах, УДАЛЁННЫХ ОТ НУЛЯ, где сами слагаемые
 * экспоненциально велики, а их разность остаётся O(1). Затронутые конфигурации:
 *  - система H (`rho = cosh`, `sigma = sinh`): в `DeBoorFixFunctionals.buildXi0`
 *    величина `rho' sigma'' - rho'' sigma'` тождественно равна 1, тогда как её
 *    масштаб `cosh^2 + sinh^2 ~ e^{2t}/2`; отношение падает ниже 1e-12 при
 *    `|t| >~ 14.2`. Аналогично вронскиан H: отношение равно `sinh(h)/sinh(2x)`,
 *    поэтому порог зависит от шага: при `h ~ 1` отбраковка начинается при
 *    `x ~ 14.2`, а на мелкой сетке порог ниже: при `h = 1/64` — уже `x ~ 12.1`;
 *  - `buildXiTilde` и прочие узловые конструкции на отрезках, удалённых от нуля
 *    на ~1e12 и более (например `[1e12, 1e12+1]`: отношение ~1.5e-14);
 *  - СИЛЬНО НЕРАВНОМЕРНЫЕ СЕТКИ на штатном отрезке `[0,1]` — это НЕ гипотетический
 *    случай. У [Grid.quasiUniform] при `amp`, близком к границе монотонности
 *    `1/(2*pi) ~ 0.15915`, шаги вблизи `u = 1/2` сжимаются как `n^-3`, и вместе
 *    с общим множителем `h^3` отношение падает как `n^-9`. Измерено для
 *    `amp = 0.158`: `n = 64` — 1.1e-11 (B), 1.2e-12 (H), 1.6e-12 (T) — ещё проходит;
 *    `n = 128` — 6.6e-13 (B), 7.0e-14 (H), 9.8e-14 (T) — УЖЕ ОТБРАКОВЫВАЕТСЯ по всем
 *    трём системам, тогда как прежний абсолютный порог проходил. При
 *    `amp = 1/(2*pi)` вырождение наступает раньше: `n = 128` — 3.3e-16 (B),
 *    `n = 1024` — 1.1e-24 (B). Снятие `require` на `amp` в [Grid.quasiUniform]
 *    легализовало именно такие значения `amp`, поэтому ограничение реально
 *    достижимо через публичный API.
 * Это осознанное сужение области определения: экспоненциальные системы на далёких
 * доменах и крайне неравномерные сетки теряют значащие разряды, и продолжение
 * счёта там дало бы молчаливый мусор. Конфигурации на РАВНОМЕРНОЙ сетке
 * (`Grid.uniform` на `[0,1]`, `n <= 256`) в это сужение не попадают.
 *
 * ГРАНИЦА ПРИМЕНИМОСТИ (осознанное решение). Критерий ловит именно ПОТЕРЮ
 * ЗНАЧИМОСТИ, а не плохую обусловленность как таковую. Матрица вида
 * `diag(1, 1, 1e-30)` вычисляется без вычитаний, её определитель достоверен,
 * и обращение по явной формуле для неё точное — такой вход критерием
 * пропускается сознательно: отбраковывать надо мусор, а не малые числа.
 */
internal const val DEGENERACY_RELATIVE_EPS = 1e-12

/**
 * Масштаб алгебраической суммы: сумма модулей её слагаемых.
 *
 * Это верхняя оценка величины, которая была бы получена без взаимных сокращений;
 * шум округления результата пропорционален именно ей. Отношение
 * `abs(sum) / cancellationScale(...)` — доля значимости, уцелевшая после вычитаний.
 */
internal fun cancellationScale(vararg terms: Double): Double {
    var s = 0.0
    for (t in terms) s += abs(t)
    return s
}

/**
 * Значима ли величина [value] на своём масштабе [scale]?
 *
 * Строгое неравенство важно для вырожденного случая `scale == 0` (все слагаемые
 * нулевые): тогда и `value == 0`, и проверка обязана дать false.
 */
internal fun isSignificant(value: Double, scale: Double): Boolean =
    abs(value) > DEGENERACY_RELATIVE_EPS * scale

/** Масштаб скалярного произведения [dot3]: сумма модулей покомпонентных произведений. */
internal fun dot3Scale(u: DoubleArray, v: DoubleArray): Double =
    abs(u[0] * v[0]) + abs(u[1] * v[1]) + abs(u[2] * v[2])

/**
 * Масштаб определителя [det3] из столбцов (c0, c1, c2): сумма модулей всех шести
 * слагаемых формулы Лейбница (знаки отброшены — нас интересует величина до сокращений).
 */
internal fun det3Scale(c0: DoubleArray, c1: DoubleArray, c2: DoubleArray): Double =
    abs(c0[0] * c1[1] * c2[2]) + abs(c0[0] * c1[2] * c2[1]) +
        abs(c0[1] * c1[0] * c2[2]) + abs(c0[1] * c1[2] * c2[0]) +
        abs(c0[2] * c1[0] * c2[1]) + abs(c0[2] * c1[1] * c2[0])
