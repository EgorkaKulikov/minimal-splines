package splines.metrics

import kotlin.math.abs

import splines.Grid

// ============================================================================
// 11. МЕТРИКИ
// ============================================================================

/**
 * Кратность измельчения контрольной сетки в [errorEh] по умолчанию: `100 * n` отрезков,
 * то есть `100n + 1` точка.
 */
const val DEFAULT_CONTROL_REFINEMENT: Int = 100

/**
 * E_h = max|u*(t) - u_h(t)| на `refinement * n + 1` точках равномерной подсетки [a, b].
 *
 * ЗАЧЕМ ПАРАМЕТР [refinement]. Равномерная норма считается по конечному набору точек,
 * поэтому она в принципе занижает истинный максимум. Убедиться, что занижения нет,
 * можно только пересчётом на измельчённой контрольной сетке — и это должна уметь сама
 * библиотека, а не обходной код в драйвере.
 *
 * ЧТО ИЗМЕРЕНО. Переход со 100n+1 на 1000n+1 точку (задача M1, полиномиальная
 * порождающая система, базовая схема, n = 32) дал максимальный относительный сдвиг
 * 4.071e-4: из 45 величин печатаемые цифры изменились у 7, и только в третьем знаке.
 * То есть значение по умолчанию максимум ошибки не занижает.
 *
 * @param refinement число отрезков контрольной сетки на один шаг основной сетки.
 * @throws IllegalArgumentException если `grid.n < 1`. Проверка дублирует контракт [Grid]
 *   (сетку с n = 0 построить нельзя), но контракт ИМЕННО этого метода — деление на
 *   m = refinement*n — фиксируем явно: при m = 0 шаг i/m дал бы 0/0 = NaN и метрика тихо
 *   вернула бы NaN вместо ошибки.
 * @throws IllegalArgumentException если `refinement < 1` — по той же причине.
 */
fun errorEh(
    exact: (Double) -> Double,
    eval: (Double) -> Double,
    grid: Grid,
    refinement: Int = DEFAULT_CONTROL_REFINEMENT,
): Double {
    require(grid.n >= 1) { "errorEh: требуется grid.n >= 1 (иначе m = refinement*n = 0), получено n=${grid.n}" }
    require(refinement >= 1) { "errorEh: требуется refinement >= 1, получено $refinement" }
    val m = refinement * grid.n
    var e = 0.0
    for (i in 0..m) {
        val t = grid.a + (grid.b - grid.a) * i / m
        e = maxOf(e, abs(exact(t) - eval(t)))
    }
    return e
}
